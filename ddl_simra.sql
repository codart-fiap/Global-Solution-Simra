
--  AREA DE RISCO, SENSORES, OCORRÊNCIAS, ALERTAS, EQUIPE DE RESGATE, ABRIGOS
CREATE TABLE T_SIM_AREA_DE_RISCO (
    id_area_de_risco NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR2(100) NOT NULL,
    localizacao VARCHAR2(100) NOT NULL,
    limiar_alerta NUMBER(4,1) NOT NULL,
    grau_de_risco VARCHAR2(5) CHECK (grau_de_risco IN ('BAIXO', 'MÉDIO', 'ALTO')) NOT NULL
);

CREATE TABLE T_SIM_SENSORES (
    id_sensor NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    localizacao VARCHAR2(100) NOT NULL,
    tipo VARCHAR2(100) NOT NULL,
    leitura_atual NUMBER(4, 1) NOT NULL,
    unidade VARCHAR2(5) NOT NULL,
   status VARCHAR2(7) CHECK (status IN ('ATIVO','INATIVO')) NOT NULL,
   id_area_de_risco NUMBER NOT NULL,
   CONSTRAINT fk_area_de_risco_sensor
    FOREIGN KEY (id_area_de_risco)
    REFERENCES T_SIM_AREA_DE_RISCO(id_area_de_risco)
);

CREATE TABLE T_SIM_OCORRENCIA_ALAGAMENTO (
    id_ocorrencia_alagamento NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    status VARCHAR2(14) CHECK (status IN ('PENDENTE','EM ATENDIMENTO','CONCLUÍDO')) NOT NULL,
    localizacao VARCHAR2(100) NOT NULL,
    descricao VARCHAR2(500) NOT NULL,
    tipo_ajuda VARCHAR2(50) NOT NULL, 
    data_hora TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    id_area_de_risco NUMBER NOT NULL,
    CONSTRAINT fk_area_de_risco_ocorrencia
    FOREIGN KEY (id_area_de_risco)
    REFERENCES T_SIM_AREA_DE_RISCO(id_area_de_risco)
);

CREATE TABLE T_SIM_ALERTA (
    id_alerta NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR2(100) NOT NULL,
    descricao VARCHAR2(500) NOT NULL,
    data_hora TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    gravidade VARCHAR2(10) CHECK (gravidade IN ('ATENÇÃO', 'CRÍTICO', 'EMERGÊNCIA')) NOT NULL,
    id_area_de_risco NUMBER NOT NULL,
    CONSTRAINT fk_area_de_risco_alerta
    FOREIGN KEY (id_area_de_risco)
    REFERENCES T_SIM_AREA_DE_RISCO(id_area_de_risco)
);

CREATE TABLE T_SIM_EQUIPE_RESGATE (
    id_equipe_resgate NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR2(100) NOT NULL,
    contato VARCHAR2(25) NOT NULL,
    disponivel NUMBER(1) DEFAULT 1 NOT NULL,
    id_area_de_risco NUMBER NOT NULL,
    CONSTRAINT fk_area_de_risco_equipe
    FOREIGN KEY (id_area_de_risco)
    REFERENCES T_SIM_AREA_DE_RISCO(id_area_de_risco)
);

-- -- ABRIGOS -> VOLUNTÁRIOS E PESSOA ABRIGADA 

CREATE TABLE T_SIM_ABRIGO (
    id_abrigo NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR2(100) NOT NULL,
    endereco VARCHAR2(200) NOT NULL,
    capacidade NUMBER(3) NOT NULL,
    vagas_disponiveis NUMBER(3) NOT NULL,
    telefone VARCHAR2(25) NOT NULL
);

CREATE TABLE T_SIM_VOLUNTARIO (
  id_voluntario NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome VARCHAR2(100) NOT NULL,
  telefone VARCHAR2(25) NOT NULL,
  especialidade VARCHAR2(50) NOT NULL,
  disponivel NUMBER(1) DEFAULT 1 NOT NULL,
  id_abrigo NUMBER NOT NULL,
  CONSTRAINT fk_abrigo_voluntario
  FOREIGN KEY (id_abrigo)
  REFERENCES T_SIM_ABRIGO(id_abrigo)
);

CREATE TABLE T_SIM_PESSOA_ABRIGADA (
    id_pessoa_abrigada NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR2(100) NOT NULL,
    idade NUMBER(3) NOT NULL,
    genero VARCHAR2(10) CHECK (genero IN ('MASCULINO', 'FEMININO', 'OUTRO')) NOT NULL,
    data_entrada TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    id_abrigo NUMBER NOT NULL,
    CONSTRAINT fk_abrigo_pessoa_abrigada
    FOREIGN KEY (id_abrigo)
    REFERENCES T_SIM_ABRIGO(id_abrigo)
);






